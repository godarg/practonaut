import type { Artifact } from '../types.ts';
import type { RawElement } from './raw.ts';
import { BROWSER_BOUNDS, bounded, closeBrowser, withClose } from '../browser/bounded.ts';
import { launchChromium } from '../browser/chromium.ts';
/** Step containers of world/1 (rectangle) and world/2 (also ellipse, diamond); checked by their box. */
const STEP_SHAPES = ['rectangle', 'ellipse', 'diamond'];
export interface RenderReport { ok: boolean; arrows: Array<{ id: string; end: string; gap: number | null; ok: boolean }>; labels: Array<{ text: string; overflow: number | null; ok: boolean }> }
/** Independent Chromium SVG layout and native coordinate checks. No Excalidraw imports. */
export async function renderCheck(artifact: Pick<Artifact, 'native' | 'svg'>, screenshotPath?: string): Promise<RenderReport> {
  const data = JSON.parse(artifact.native) as { elements: RawElement[] };
  const live = data.elements.filter(e => !e.isDeleted), arrows: RenderReport['arrows'] = [];
  for (const arrow of live.filter(e => e.type === 'arrow')) {
    for (const end of ['start', 'end'] as const) {
      const binding = end === 'start' ? arrow.startBinding : arrow.endBinding;
      const target = live.find(e => e.id === binding?.elementId && STEP_SHAPES.includes(e.type));
      const point = end === 'start' ? arrow.points?.[0] : arrow.points?.at(-1);
      if (!target || !point) { arrows.push({ id: arrow.id, end, gap: null, ok: false }); continue; }
      const x = arrow.x + point[0]!, y = arrow.y + point[1]!;
      const outside = Math.hypot(Math.max(target.x - x, x - target.x - target.width, 0), Math.max(target.y - y, y - target.y - target.height, 0));
      const inside = Math.min(Math.abs(x - target.x), Math.abs(x - target.x - target.width), Math.abs(y - target.y), Math.abs(y - target.y - target.height));
      const gap = outside || inside;
      arrows.push({ id: arrow.id, end, gap, ok: gap <= 12 });
    }
  }
  const { chromium } = await bounded(import('playwright-core'), BROWSER_BOUNDS.launch, 'launch');
  const { browser } = await launchChromium(chromium, () => ({ headless: true }));
  // The browser closes within its bound; a failed close never replaces the check's own failure (issue #64).
  return withClose(async (): Promise<RenderReport> => {
    const context = await browser.newContext({ serviceWorkers: 'block' });
    await context.route('**/*', route => route.abort());
    const page = await context.newPage();
    // SVG is data generated by our exporter. No scripts or remote images are allowed by the CSP.
    await page.setContent('<meta http-equiv="Content-Security-Policy" content="default-src \'none\';style-src \'unsafe-inline\';font-src data:;img-src data:"><body style="margin:0">' + artifact.svg);
    await page.evaluate('document.fonts.ready');
    const layout = await page.evaluate(`(() => {
      const svg = document.querySelector('svg'), rect = svg.getBoundingClientRect();
      const anchors = [...svg.querySelectorAll('clipPath')].map(c => {
        const box = c.querySelector('rect'), m = /translate\\(([-\\d.]+) ([-\\d.]+)\\)/.exec(box?.getAttribute('transform') ?? '');
        return { id: c.id, x: m ? Number(m[1]) : null, y: m ? Number(m[2]) : null };
      });
      const texts = [...svg.querySelectorAll('text')].map(t => {
        const b = t.getBoundingClientRect(), matrix = t.parentElement.getCTM();
        const clip = t.closest('g[clip-path]')?.getAttribute('clip-path');
        return { text: t.textContent, x: b.left-rect.left, y: b.top-rect.top, width: b.width, height: b.height,
          groupX: matrix?.e ?? null, groupY: matrix?.f ?? null, frameId: clip?.startsWith('url(#') ? clip.slice(5, -1) : null };
      });
      return { anchors, texts };
    })()`) as { anchors: Array<{ id: string; x: number | null; y: number | null }>; texts: Array<{ text: string; x: number; y: number; width: number; height: number; groupX: number | null; groupY: number | null; frameId: string | null }> };
    const labels: RenderReport['labels'] = [];
    for (const nativeText of live.filter(e => e.type === 'text' && e.containerId)) {
      const box = live.find(e => e.id === nativeText.containerId && STEP_SHAPES.includes(e.type));
      if (!box || Math.abs(nativeText.x + nativeText.width / 2 - box.x - box.width / 2) > 1 || Math.abs(nativeText.y + nativeText.height / 2 - box.y - box.height / 2) > 1) labels.push({ text: nativeText.originalText ?? '', overflow: null, ok: false });
    }
    // The export translates every element by one offset. A frame's clip anchor measures it; without
    // any frame, frameless labels bind by the single offset that their text groups agree on.
    const anchored = live.filter(e => e.type === 'frame').map(frame => ({ frame, anchor: layout.anchors.find(a => a.id === frame.id) })).find(item => item.anchor?.x != null && item.anchor.y != null);
    let global = anchored ? { dx: anchored.anchor!.x! - anchored.frame.x, dy: anchored.anchor!.y! - anchored.frame.y } : undefined;
    if (!global) {
      const votes = new Map<string, number>();
      for (const text of layout.texts) for (const e of live) if (e.type === 'text' && e.containerId && e.frameId === null && (e.text?.split('\n').includes(text.text) || e.originalText === text.text) && text.groupX != null && text.groupY != null) {
        const key = `${Math.round(text.groupX - e.x)},${Math.round(text.groupY - e.y)}`; votes.set(key, (votes.get(key) ?? 0) + 1);
      }
      const best = [...votes.entries()].sort((a, b) => b[1] - a[1]);
      if (best[0] && (best.length === 1 || best[0][1] > best[1]![1])) { const [dx, dy] = best[0][0].split(',').map(Number); global = { dx: dx!, dy: dy! }; }
    }
    for (const text of layout.texts) {
      if (!text.frameId && live.some(e => e.type === 'frame' && e.name === text.text)) continue;
      const frame = live.find(e => e.type === 'frame' && e.id === text.frameId);
      const anchor = layout.anchors.find(a => a.id === frame?.id);
      const framed = !!frame && anchor?.x != null && anchor.y != null;
      if ((text.frameId ? !framed : !global) || text.groupX == null || text.groupY == null) { labels.push({ text: text.text, overflow: null, ok: false }); continue; }
      const dx = framed ? anchor!.x! - frame!.x : global!.dx, dy = framed ? anchor!.y! - frame!.y : global!.dy;
      // A wrapped word can occur in many labels. Bind the SVG text group to its native text
      // object by the group transform, then check its real glyph bounds against that object's box.
      // A displaced or unknown group fails instead of being assigned to a convenient nearby box.
      const matches = live.filter(e => e.type === 'text' && e.frameId === (framed ? frame!.id : null) && e.containerId &&
        Math.abs(e.x + dx - text.groupX!) <= 0.5 && Math.abs(e.y + dy - text.groupY!) <= 0.5 &&
        (e.text?.split('\n').includes(text.text) || e.originalText === text.text));
      const nativeText = matches.length === 1 ? matches[0] : undefined;
      const container = live.find(e => STEP_SHAPES.includes(e.type) && e.id === nativeText?.containerId);
      if (!container) { labels.push({ text: text.text, overflow: null, ok: false }); continue; }
      const overflow = Math.max(container.x - (text.x - dx), text.x + text.width - dx - container.x - container.width, container.y - (text.y - dy), text.y + text.height - dy - container.y - container.height, 0);
      labels.push({ text: text.text, overflow, ok: overflow <= 2 });
    }
    if (screenshotPath) await page.locator('svg').first().screenshot({ path: screenshotPath });
    return { ok: arrows.every(a => a.ok) && labels.every(l => l.ok) && labels.length > 0, arrows, labels };
  }, () => closeBrowser(browser));
}
